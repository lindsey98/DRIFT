"""Trust-separation threat model for the AgentDojo suites.

Attack surface premise: the benign content a task must trust and the attacker's payload must live in
SEPARABLE containers -- a different record (another email, review, issue, calendar event, DM, web ad) or
a distinct field of a structured record (a transaction's subject, an event's description, while the task
needs its date). Those boundaries are what the defense's reader keys on, so such injections are IN scope.

OUT of scope (CO_LOCATED): the payload is mixed into one UNSTRUCTURED text blob -- a .txt bill, a notice,
a file, a document -- that the task is told to read and act on wholesale ("pay the bill, instructions are
in it", "read landlord-notices.txt and adjust accordingly", "sum the payments in the invoices"). Benign
instruction and payload share a single blob with no structural boundary, so no defense can separate them.
These (task) pairs are dropped: a defense is not charged for a case that is unsolvable by construction.

CO_LOCATED[suite] is the per-TASK drop set: co-location depends on whether THIS task consumes the injected
document as content, not merely on where a vector lives (listing a file surfaces its content without
consuming it, so a per-vector rule over-drops). Each entry was ruled from the task's own prompt.

VECTOR_CLASS labels each vector SEP / COLOC by whether it is an unstructured document (for the fork
re-run: inject only into SEP vectors). SURFACED[suite][task] is the vectors a correct run exposes
(AgentDojo GroundTruthPipeline + canary; deterministic). qualifying_tasks = injectable - CO_LOCATED.

PROVISIONAL: the primary suites (banking/slack/travel/workspace) are finalised from prompt evidence. The
dynamic suites (github/shopping/dailylife) ship placeholder descriptions and a pervasive "follow the
instructions in this email/website/document" structure; only high-confidence drops are listed and the
rest need a dedicated pass -- treat their CO_LOCATED as a lower bound. Regenerate with scratchpad
gen_module2.py over a fresh get_injection_candidates sweep.
"""
