def injectable_tasks(suite: str) -> set[str]:
    """Tasks whose correct execution surfaces at least one injection vector (AgentDojo-injectable)."""
    return {t for t, vs in SURFACED.get(suite, {}).items() if vs}


def qualifying_tasks(suite: str) -> set[str]:
    """Injectable tasks that are IN scope: the payload is separable from the task's trusted content."""
    return injectable_tasks(suite) - CO_LOCATED.get(suite, set())


def separated_vectors(suite: str) -> set[str]:
    """Vectors the fork re-run may inject into (payload in its own container)."""
    return {v for v, k in VECTOR_CLASS.get(suite, {}).items() if k == "SEP"}
